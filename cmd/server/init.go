// File names inside a data directory.
const (
	keyFileName    = "server.key"
	certFileName   = "server.crt"
	configFileName = "server.toml"
)

// Unix permissions for the data directory and its files. The private key
// must be readable by the server account only. The certificate and
// configuration are not secret, but there is no reason for anyone else to
// read them either. Go ignores these modes on Windows, where init applies
// explicit access control lists instead (see datadir_windows.go).
const (
	dataDirMode  fs.FileMode = 0o700
	dataFileMode fs.FileMode = 0o600
)

const configHeader = "# qchat-server configuration, generated by \"qchat-server init\".\n# Relative paths are resolved against the directory of this file.\n\n"

// cmdInit creates a data directory holding a new server identity, a
// configuration file and the database of identities and invites, then
// prints the fingerprint clients must pin.
//
// It refuses to replace an existing identity or configuration unless
// --force is given, because a new key changes the fingerprint and every
// client pinned to the old one stops connecting. It also refuses to use an
// existing directory that another account controls or that other users
// may read or write, because whoever controls the directory can read or
// replace the key.
//
// An existing database is kept, also with --force: it holds no secret tied
// to the server key, and deleting it would drop every registered identity.
//
// The database lives in a directory of its own (db/ by default, or the
// directory of --database), because SQLite needs write access to that
// directory for its -wal and -shm files while the key and configuration
// stay read-only for the server account.
func cmdInit(args []string, stdout, stderr io.Writer) error {
	fset := newFlagSet("init", "--data-dir DIR [--host NAME]... [--listen ADDR] [--database PATH] [--service-account NAME] [--force]", stderr)
	dataDir := fset.String("data-dir", "", "directory for server.key, server.crt, server.toml and the database (required)")
	var hosts stringList
	fset.Var(&hosts, "host", "host name or IP address clients use to reach the server; repeatable (default localhost)")
	listen := fset.String("listen", server.DefaultListen, "address the server listens on")
	database := fset.String("database", server.DefaultDatabase, "database file, in a directory the server may write to; relative paths resolve against --data-dir (for systemd: /var/lib/qchat/qchat.db)")
	serviceAccount := fset.String("service-account", "", "Windows only: account or SID that runs the service and gets read access, e.g. \"NT SERVICE\\qchat-server\"")
	force := fset.Bool("force", false, "replace an existing identity and configuration")
	if err := parseFlags(fset, args); err != nil {
		return err
	}
	if *dataDir == "" {
		return usagef(fset, "--data-dir is required")
	}
	if len(hosts) == 0 {
		hosts = stringList{"localhost"}
	}

	cfg := server.DefaultConfig()
	cfg.Listen = *listen
	cfg.Database = *database
	if err := cfg.Validate(); err != nil {
		return err
	}
	dbPath := *database
	if !filepath.IsAbs(dbPath) {
		dbPath = filepath.Join(*dataDir, dbPath)
	}
	dbDir := filepath.Dir(dbPath)
	sharesDataDir := sameDirectory(dbDir, *dataDir)
	if sharesDataDir && *serviceAccount != "" {
		return usagef(fset, "--database must not be directly in --data-dir when --service-account is given: the service account needs write access to the database directory, but only read access to the key")
	}

	protection, err := prepareDataDir(*dataDir, *serviceAccount, stderr)
	if err != nil {
		return err
	}
	if !sharesDataDir {
		if err := protection.prepareDatabaseDir(dbDir, stderr); err != nil {
			return err
		}
	}

	keyPath := filepath.Join(*dataDir, keyFileName)
	certPath := filepath.Join(*dataDir, certFileName)
	configPath := filepath.Join(*dataDir, configFileName)
	if !*force {
		for _, path := range []string{keyPath, certPath, configPath} {
			if _, err := os.Lstat(path); err == nil {
				return fmt.Errorf("%s already exists; use --force to replace it (a new key changes the fingerprint, and clients pinned to the old one stop connecting)", path)
			} else if !errors.Is(err, fs.ErrNotExist) {
				return err
			}
		}
	}

	certPEM, keyPEM, err := transport.GenerateServerIdentity(hosts)
	if err != nil {
		return err
	}
	defer clear(keyPEM)

	var configTOML bytes.Buffer
	configTOML.WriteString(configHeader)
	if err := cfg.WriteTOML(&configTOML); err != nil {
		return err
	}

	if err := createDatabase(dbPath, protection); err != nil {
		return err
	}

	if err := writeFileAtomic(keyPath, keyPEM, protection); err != nil {
		return fmt.Errorf("write private key: %w", err)
	}
	if err := writeFileAtomic(certPath, certPEM, protection); err != nil {
		return fmt.Errorf("write certificate: %w", err)
	}
	if err := writeFileAtomic(configPath, configTOML.Bytes(), protection); err != nil {
		return fmt.Errorf("write config: %w", err)
	}

	cert, err := transport.LoadServerCertificate(certPath, keyPath)
	if err != nil {
		return err
	}
	pin, err := transport.FingerprintOfTLS(cert)
	if err != nil {
		return err
	}

	_, port, err := net.SplitHostPort(cfg.Listen)
	if err != nil {
		return err
	}
	fmt.Fprintf(stdout, "Created server identity, configuration and database in %s\n", *dataDir)
	fmt.Fprintf(stdout, "  private key: %s (secret: never share or copy it)\n", keyPath)
	fmt.Fprintf(stdout, "  certificate: %s\n", certPath)
	fmt.Fprintf(stdout, "  database:    %s\n", dbPath)
	fmt.Fprintf(stdout, "  config:      %s\n\n", configPath)
	printFingerprint(stdout, pin)
	fmt.Fprintf(stdout, "\nClients connect with:\n  qchat --server %s --pin %s\n", net.JoinHostPort(hosts[0], port), pin)
	return nil
}

// printFingerprint writes both forms of the fingerprint: the canonical one
// for configuration and command lines, and the grouped one for comparing by
// eye or reading aloud.
func printFingerprint(w io.Writer, pin transport.Fingerprint) {
	fmt.Fprintf(w, "Server fingerprint:\n  %s\n  %s\n", pin.String(), pin.Grouped())
}

// writeFileAtomic writes content to a temporary file in the target
// directory and renames it into place, so a crash never leaves a truncated
// key or configuration behind. The temporary file is created with the
// restricted permissions of protection from the start, so there is no
// moment in which others can read the content.
func writeFileAtomic(path string, content []byte, protection *fileProtection) error {
	tmp, err := protection.createTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	committed := false
	defer func() {
		if !committed {
			_ = tmp.Close()
			_ = os.Remove(tmpPath)
		}
	}()
	if _, err := tmp.Write(content); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return err
	}
	committed = true
	return nil
}

// sameDirectory reports whether two paths name the same directory after
// cleaning; it does not resolve links.
func sameDirectory(a, b string) bool {
	absA, errA := filepath.Abs(a)
	absB, errB := filepath.Abs(b)
	if errA != nil || errB != nil {
		return filepath.Clean(a) == filepath.Clean(b)
	}
	return absA == absB || (runtime.GOOS == "windows" && strings.EqualFold(absA, absB))
}

// createDatabase creates the database file at path with the protection of
// the database directory and applies the schema. An existing database is
// opened and migrated, never replaced. SQLite's -wal and -shm files, which
// exist only while the database is open, inherit the database directory's
// ACL on Windows and the main file's mode on Unix.
func createDatabase(path string, protection *fileProtection) error {
	if err := protection.createDatabaseFile(path); err != nil {
		return fmt.Errorf("create database: %w", err)
	}
	db, err := serverdb.Open(path)
	if err != nil {
		return fmt.Errorf("create database: %w", err)
	}
	if err := db.Close(); err != nil {
		return fmt.Errorf("create database: %w", err)
	}
	return nil
}
